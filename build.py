def dstyle(t):
    """IAST -> the dataset's spelling convention (ṣ->ṣh, ś->śh, c->ch, ch->chh, ṛ->ṛi, ṃ->ṁ)."""
    t = t.replace("ch", "\x01").replace("c", "ch").replace("\x01", "chh")
    return t.replace("ś", "śh").replace("ṣ", "ṣh").replace("ṛ", "ṛi").replace("ṃ", "ṁ")


