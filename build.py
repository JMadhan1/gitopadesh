for _l in ("hi", "te"):
    _p = f"data/i18n/{_l}.json"
    if not os.path.exists(_p):
        continue
    _src = json.load(open(_p, encoding="utf8"))
    _rx = re.compile(r"[\u0900-\u097F]" if _l == "hi" else r"[\u0C00-\u0C7F]")
    _out, _warn = {}, []
    for v in verses:
        k = f"{v['chapter']}.{v['verse']}"
        j = _src.get(k) or {}
        t = re.sub(r"[।॥|]+\s*\d+[.\-–]\d+\s*[।॥|]+", "", (j.get("t") or "")).strip()
        if not t or len(_rx.findall(t)) < 0.5 * len(re.sub(r"[\s\W\d]", "", t) or "x"):
            _warn.append(k)
            continue
        pairs = [p for p in (j.get("w") or []) if isinstance(p, list) and len(p) == 2]
        wtxt = "; ".join(f"{a}—{b}" if b else a for a, b in pairs)
        _out[k] = {"t": t, "w": wtxt}
    w(f"verses.{_l}.json", json.dumps(_out, ensure_ascii=False, separators=(",", ":")))
    print(f"i18n {_l}: {len(_out)} verses, skipped {len(_warn)} {_warn[:8]}")

